-- 009 – מפתח hebcal של שבועות.
--
-- מיגרציות 001–008 קפואות. 008 כבר הוחלה, ולכן התיקון הזה בקובץ חדש.
--
-- אותו סוג באג כמו ב-008: בטבלה נרשם `Shavuot I` (מזהה `getHolidaysOnDate`
-- בגרסה ישנה), בעוד ש-hebcal מחזיר `Shavuot` בלבד. הוא לא נתפס ב-008 כי
-- הסריקה שם הייתה על `getSedra` בלבד – ושבועות **לעולם אינו חל בשבת**
-- (כלל "לא בד"ו פסח" קובע את ימי השבוע האפשריים), ולכן הוא לא הופיע שם
-- כמפתח שבת חסר.
--
-- עד עכשיו זה היה ערך מת בלבד. מרגע ש-`defaultOccasionFor` בוחר חג ביום
-- חול (F-31), המפתח הזה נדרש בפועל: בלעדיו נדר שנודר בשבועות היה מקבל
-- כברירת מחדל את הפרשה של השבת שקדמה.

UPDATE occasion SET hebcal_key = 'Shavuot'
  WHERE name = 'שבועות' AND (hebcal_key IS NULL OR hebcal_key = 'Shavuot I');
