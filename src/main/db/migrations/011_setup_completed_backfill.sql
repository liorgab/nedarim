-- 011 – התקנה שכבר הוגדרה לא צריכה לראות את אשף ההתקנה.
--
-- מיגרציות 001–010 קפואות.
--
-- מיגרציה 010 הוסיפה `setup_completed_at` ריק לכולם, ולכן האשף נפתח גם
-- במערכות שעובדות מזה חודשים ומלאות בנתונים. זה התגלה בהתקנה אמיתית:
-- מערכת עם 90 חברים וקבלות קיבלה מסך "ברוך הבא – הגדרה ראשונה".
--
-- הקריטריון הוא שם בית הכנסת: הוא שדה החובה היחיד, והוא מודפס על כל
-- קבלה. אם הוא מולא – מישהו כבר עבר על ההגדרות, והאשף מיותר. מי שירצה
-- אותו בכל זאת יכול לפתוח אותו מהגדרות ← אודות ורישוי.
--
-- מסומן בתאריך ריק-משמעותי ולא ב-`datetime('now')`: זה לא מועד שבו
-- הגבאי סיים אשף, אלא סימון שהמערכת הייתה מוגדרת עוד לפני שהאשף נולד.
UPDATE setting
SET value = 'pre-wizard'
WHERE key = 'setup_completed_at'
  AND (value IS NULL OR TRIM(value) = '')
  AND EXISTS (
    SELECT 1 FROM setting s
    WHERE s.key = 'synagogue_name' AND TRIM(COALESCE(s.value, '')) <> ''
  );
