-- 013 – קבלה על שם אחר (F-76), והגדרת מצב ניהול השם (F-13).
--
-- מיגרציות 001–012 קפואות.
--
-- **קבלה על שם אחר:** לעיתים התשלום נעשה על ידי החבר אבל הקבלה נדרשת על
-- שם אחר – חברה בע"מ, עמותה, או בן משפחה. עד היום שם המשלם על הקבלה נגזר
-- תמיד משם החבר, ולא הייתה שום דרך לשנות זאת בלי לשנות את שם החבר עצמו.
--
-- העמודה יושבת על **התשלום ועל התרומה**, ולא רק על הקבלה: הקבלה מקפיאה
-- את `payer_name` בהפקה (B-04), וכשמבטלים ומפיקים מחדש צריך לדעת שוב על
-- שם מי. בלי זה כל הפקה חוזרת הייתה חוזרת לשם החבר בשקט.
--
-- `NULL` = הקבלה על שם החבר/התורם, כמו עד היום.

ALTER TABLE vow_payment ADD COLUMN receipt_name TEXT;
ALTER TABLE donation ADD COLUMN receipt_name TEXT;

-- F-13 – האם השם מנוהל כשדה אחד או כשניים.
--
-- `split` (ברירת המחדל) = שם פרטי ושם משפחה בנפרד, כפי שהיה עד היום.
-- `full` = שדה אחד. הערך נשמר ב-`first_name` ו-`last_name` נשאר ריק,
-- ולכן מעבר בין המצבים אינו מאבד דבר ואינו דורש המרה: בית כנסת שניהל
-- שם מלא יכול לעבור ל-`split` ולמלא את שם המשפחה חבר-חבר.
INSERT OR IGNORE INTO setting (key, value) VALUES ('member_name_mode', 'split');
